#!/usr/bin/env python3
"""Generate src/wcwidth.h: display-width ranges like libcpp's cpp_wcwidth.

Zero width: combining marks (Mn, Me), format characters (Cf), Hangul Jamo
medial vowels and final consonants (U+1160..U+11FF).  Width 2: East Asian
Wide and Fullwidth.  usage: gen_wcwidth.py > src/wcwidth.h
"""
import sys
import unicodedata as ud


def ranges(pred):
    out, lo = [], None
    for cp in range(0x110000):
        if pred(cp):
            if lo is None:
                lo = cp
            hi = cp
        elif lo is not None:
            out.append((lo, hi))
            lo = None
    if lo is not None:
        out.append((lo, hi))
    return out


def zero(cp):
    if 0x1160 <= cp <= 0x11FF:
        return True
    return ud.category(chr(cp)) in ("Mn", "Me", "Cf")


def wide(cp):
    return ud.east_asian_width(chr(cp)) in ("W", "F") and not zero(cp)


print("/* Generated by bench/tools/gen_wcwidth.py (Unicode %s); do not edit. */"
      % ud.unidata_version)
for name, pred in (("wc_zero", zero), ("wc_wide", wide)):
    r = ranges(pred)
    print("static const struct { unsigned lo, hi; } %s[] = {" % name)
    for i in range(0, len(r), 4):
        print("    " + " ".join("{0x%X, 0x%X}," % x for x in r[i:i + 4]))
    print("};")
